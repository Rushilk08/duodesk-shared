export function loadSnapshot(): WorkspaceStateSnapshot {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      const seeded = buildSeedSnapshot();
      localStorage.setItem(STORAGE_KEY, JSON.stringify(seeded));
      return seeded;
    }
    return JSON.parse(raw) as WorkspaceStateSnapshot;
  } catch {
    return buildSeedSnapshot();
  }
}

export function saveSnapshot(snapshot: WorkspaceStateSnapshot): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(snapshot));
  } catch {
    // Handle storage quota gracefully without crashing prototype
  }
}

export function resetSnapshot(): WorkspaceStateSnapshot {
  const fresh = buildSeedSnapshot();
  saveSnapshot(fresh);
  return fresh;
}

export function isVisibleToUser(
  item: { visibility: 'private' | 'shared'; ownerId?: UserId },
  userId: UserId
): boolean {
  if (item.visibility === 'shared') return true;
  return item.ownerId === userId;
}
